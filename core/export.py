"""
core/export.py
==============
Utilities to export conversation history to Markdown and Plain Text formats.

Excludes internal tool traces, system prompts, API keys, and internal state.
"""

from __future__ import annotations

from datetime import datetime
from typing import List, Dict, Any


def export_to_markdown(messages: List[Dict[str, Any]], title: str = "Conversation") -> str:
    """
    Format conversation history as a clean Markdown document.
    """
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    lines = [
        f"# {title}",
        f"*Exported on {now_str}*",
        "",
        "---",
        "",
    ]

    for msg in messages:
        role = msg.get("role", "unknown")
        content = (msg.get("content") or "").strip()
        agent = msg.get("agent_name")

        if role == "user":
            lines.append("### 👤 User")
            lines.append(content)
            lines.append("")
        elif role == "assistant":
            badge = f" ({agent} Agent)" if agent else ""
            lines.append(f"### 🤖 Assistant{badge}")
            lines.append(content)
            lines.append("")

    lines.append("---")
    lines.append("*Generated by Multi-Agent AI Research Assistant*")
    return "\n".join(lines)


def export_to_txt(messages: List[Dict[str, Any]], title: str = "Conversation") -> str:
    """
    Format conversation history as a clean plain text document.
    """
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    separator = "=" * 70
    sub_separator = "-" * 70

    lines = [
        separator,
        f" CONVERSATION: {title}",
        f" Exported on: {now_str}",
        separator,
        "",
    ]

    for msg in messages:
        role = msg.get("role", "unknown")
        content = (msg.get("content") or "").strip()
        agent = msg.get("agent_name")

        if role == "user":
            lines.append("[USER]:")
            lines.append(content)
            lines.append("")
            lines.append(sub_separator)
            lines.append("")
        elif role == "assistant":
            badge = f" ({agent})" if agent else ""
            lines.append(f"[ASSISTANT{badge}]:")
            lines.append(content)
            lines.append("")
            lines.append(sub_separator)
            lines.append("")

    return "\n".join(lines)

